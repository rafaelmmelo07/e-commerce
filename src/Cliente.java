public class Cliente {
    private String cpf;
    private String nome;
    private Integer id;

    public Cliente(){}


    public String getNome() {
        return nome;
    }

    public String getCpf() {
        return cpf;
    }

    public Integer getId() {
        return id;
    }

    public void setId(Integer id) {
        this.id = id;
    }

    public void setCpf(String cpf){
        this.id = id;
    }
}
